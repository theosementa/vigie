// Vendors the brand logos listed in src/components/brands.txt into src/components/brands.ts.
// Run with `npm run brands`; needs @iconify-json/simple-icons as a devDependency.
// Logos are embedded so the PWA never fetches a favicon from a third party. Simple Icons is CC0;
// the logos remain trademarks of their owners.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const set = createRequire(import.meta.url)('@iconify-json/simple-icons/icons.json')
const names = readFileSync('src/components/brands.txt', 'utf8').split('\n').map((s) => s.trim()).filter((s) => s && !s.startsWith('#'))

const body = (name) => {
  const icon = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent]
  if (!icon) throw new Error(`Unknown Simple Icons logo: ${name}`)
  return icon.body.replace(/ fill="currentColor"/g, '')
}

const lines = [...new Set(names)].sort().map((n) => `  '${n}': ${JSON.stringify(body(n))},`)
writeFileSync(
  'src/components/brands.ts',
  `// Generated by \`npm run brands\` from @iconify-json/simple-icons (CC0). Do not edit. Logos are trademarks of their owners.\nexport const BRANDS = {\n${lines.join('\n')}\n} as const\n\nexport type BrandName = keyof typeof BRANDS\n`,
)
console.log(`brands.ts: ${lines.length} logos`)
