// Vendors the Solar icons listed in src/components/icons.txt into src/components/icons.ts.
// Run with `npm run icons` ("icons": "node scripts/icons.mjs"); needs @iconify-json/solar as a devDependency.
// Icons are embedded so the PWA never fetches them at runtime. Solar Icon Set by 480 Design, CC BY 4.0.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const set = createRequire(import.meta.url)('@iconify-json/solar/icons.json')
const names = readFileSync('src/components/icons.txt', 'utf8').split('\n').map((s) => s.trim()).filter((s) => s && !s.startsWith('#'))

const body = (name) => {
  const icon = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent]
  if (!icon) throw new Error(`Unknown Solar icon: ${name}`)
  return icon.body
}

const lines = [...new Set(names)].sort().map((n) => `  '${n}': ${JSON.stringify(body(n))},`)
writeFileSync(
  'src/components/icons.ts',
  `// Generated by \`npm run icons\` from @iconify-json/solar (Solar Icon Set by 480 Design, CC BY 4.0). Do not edit.\nexport const ICONS = {\n${lines.join('\n')}\n} as const\n\nexport type IconName = keyof typeof ICONS\n`,
)
console.log(`icons.ts: ${lines.length} icons`)
